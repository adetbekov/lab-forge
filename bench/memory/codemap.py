"""Generated code map: one line per module with its top-level classes and functions.

Experiment tool for the JEB-1882 memory spike (bench/memory/results.md); not shipped.
Stdlib only. Deterministic, so it is never stale: regenerate it, never edit it.
If the map is over budget, method lists go first, then private names.

Usage:
    python codemap.py <project> [--out .lab-forge/map.md] [--budget 24000]
"""

import argparse
import ast
from pathlib import Path

SKIP = {".git", ".venv", "venv", "node_modules", "__pycache__", "build", "dist", "site", "docs",
        "tests", "test", "examples", "notebooks", "benchmarks", "tutorial", "alembic"}
FUNC = (ast.FunctionDef, ast.AsyncFunctionDef)


def modules(root):
    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root)
        if not any(p in SKIP or p.startswith(".") for p in rel.parts[:-1]):
            yield rel


def line(rel, tree, methods, private):
    names = []
    for node in tree.body:
        if not isinstance(node, (ast.ClassDef, *FUNC)) or (node.name.startswith("_") and not private):
            continue
        name = node.name
        if isinstance(node, ast.ClassDef) and methods:
            public = [n.name for n in node.body if isinstance(n, FUNC) and not n.name.startswith("_")]
            name += f"[{', '.join(public)}]" if public else ""
        names.append(name)
    return f"- `{rel.as_posix()}`" + (f": {', '.join(names)}" if names else "")


def build(root, budget):
    trees = {}
    for rel in modules(root):
        try:
            trees[rel] = ast.parse((root / rel).read_text(encoding="utf-8", errors="ignore"))
        except SyntaxError:
            continue
    head = [f"# Code map ({len(trees)} modules)", "",
            "Generated by lab-forge `codemap.py`; never edit. Top-level classes [public methods] and functions.", ""]
    for methods, private in ((True, True), (False, True), (False, False)):
        body = [line(rel, tree, methods, private) for rel, tree in trees.items()]
        text = "\n".join(head + body) + "\n"
        if len(text) <= budget:
            return text
    return text[:budget].rsplit("\n", 1)[0] + "\n- ... cut at budget\n"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("project")
    p.add_argument("--out", default=".lab-forge/map.md", help="relative to the project")
    p.add_argument("--budget", type=int, default=24000, help="characters, about 4 per token")
    args = p.parse_args()
    root = Path(args.project).resolve()
    dest = root / args.out
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(build(root, args.budget))
    print(dest)


if __name__ == "__main__":
    main()
